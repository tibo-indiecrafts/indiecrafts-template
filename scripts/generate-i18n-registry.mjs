#!/usr/bin/env node
/**
 * Auto-generate the i18n aggregators from filesystem scan.
 *
 * Walks `src/components/**` for `en.json` files (one per
 * section/template/chrome bit), reads the sibling `config.ts` to extract
 * the canonical block key (`export const <name>Key = "<key>" as const`),
 * and emits two committed files:
 *
 *   - src/i18n/block-messages.ts  : runtime aggregator (imports + map +
 *                                   loadBlockMessages helper)
 *   - src/types/messages.ts       : compile-time type tree feeding
 *                                   the `MessageKey` dotted-path union
 *
 * Both files carry a "DO NOT EDIT — run `pnpm gen:i18n`" header. Drift
 * is caught in CI by `pnpm verify:i18n` (regen + diff).
 *
 * Special cases:
 *   - Flat `<key>.en.json` (e.g. `ui-effects/3d-pin.en.json`) → key
 *     derived from the filename.
 *   - en.json folders without a sibling config.ts are skipped with a
 *     warning (we have none today; the warning surfaces accidental adds).
 */

import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative, dirname, basename } from "node:path";
import { spawnSync } from "node:child_process";

const ROOT = process.cwd();
const COMPONENTS_DIR = join(ROOT, "src/components");
const I18N_OUT = join(ROOT, "src/i18n/block-messages.ts");
const TYPES_OUT = join(ROOT, "src/types/messages.ts");

const HEADER = `// AUTO-GENERATED by scripts/generate-i18n-registry.mjs
// DO NOT EDIT — run \`pnpm gen:i18n\` to regenerate. Drift caught by \`pnpm verify:i18n\`.
`;

function walk(dir, files = []) {
  for (const e of readdirSync(dir)) {
    const f = join(dir, e);
    const st = statSync(f);
    if (st.isDirectory()) {
      if (e === "node_modules") continue;
      walk(f, files);
    } else if (e === "en.json" || e.endsWith(".en.json")) {
      files.push(f);
    }
  }
  return files;
}

const KEY_RE = /export const \w+Key = "([^"]+)" as const/;

function deriveKey(absPath) {
  const file = basename(absPath);
  if (file !== "en.json") {
    // Flat `<key>.en.json` form (single special case today).
    return file.replace(/\.en\.json$/, "");
  }
  const folder = dirname(absPath);
  // Prefer the canonical `<name>Key = "<key>"` declared in sibling
  // config.ts. Falls back to the folder name (kebab-cased), which works
  // for sections that haven't declared a key constant yet — folder name
  // IS the convention.
  const configPath = join(folder, "config.ts");
  try {
    const src = readFileSync(configPath, "utf8");
    const m = src.match(KEY_RE);
    if (m) return m[1];
  } catch {
    // no config.ts — fall through to folder fallback
  }
  return basename(folder);
}

function camelCase(kebab) {
  const out = kebab.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  // JavaScript identifiers can't start with a digit (`3d-pin` →
  // `3dPin` would be illegal). Prefix with underscore in that case.
  return /^[a-z_$]/i.test(out) ? out : `_${out}`;
}

const enFiles = walk(COMPONENTS_DIR);
const entries = [];
for (const file of enFiles) {
  const key = deriveKey(file);
  if (!key) {
    console.warn(
      `! skipping ${relative(ROOT, file)} — no <name>Key in sibling config.ts`,
    );
    continue;
  }
  const importPath = relative(dirname(I18N_OUT), file).replace(/\\/g, "/");
  // ../components/... — the "../" prefix is required because relative()
  // doesn't add one when the source lives in a sibling directory.
  const normalizedImport = importPath.startsWith(".") ? importPath : `./${importPath}`;
  const aliasPath = `@/components/${relative(COMPONENTS_DIR, file).replace(/\\/g, "/")}`;
  entries.push({
    key,
    varName: `${camelCase(key)}En`,
    importPath: normalizedImport,
    aliasPath,
  });
}

entries.sort((a, b) => a.key.localeCompare(b.key));

// ── runtime aggregator ──────────────────────────────────────────────
const blockImports = entries
  .map((e) => `import ${e.varName} from "${e.importPath}";`)
  .join("\n");
const blockMap = entries.map((e) => `  "${e.key}": ${e.varName},`).join("\n");

const blockMessagesContent = `${HEADER}
${blockImports}

const BLOCK_MESSAGES: Record<string, Record<string, unknown>> = {
${blockMap}
};

/**
 * Returns \`{ "<block-key>": {...}, ... }\` merged as-is. Non-English
 * locales fall back to the English sample — clients fill in real
 * translations per page when they customize.
 */
export function loadBlockMessages(): Record<string, unknown> {
  return { ...BLOCK_MESSAGES };
}
`;

writeFileSync(I18N_OUT, blockMessagesContent);

// ── type tree ────────────────────────────────────────────────────────
const typeImports = entries
  .map((e) => `import type ${e.varName} from "${e.aliasPath}";`)
  .join("\n");
const typeFields = entries.map((e) => `    "${e.key}": typeof ${e.varName};`).join("\n");

const typesContent = `${HEADER}
import type globalEn from "../../messages/en.json";

// ── per-page route messages (hand-maintained — co-located with each route) ──
import type homeEn from "@/app/[locale]/messages/en.json";
import type aboutEn from "@/app/[locale]/about/messages/en.json";

// ── per-block / per-template messages (auto-discovered) ─────────────
${typeImports}

type MergedMessages = typeof globalEn & {
  pages: {
    home: typeof homeEn;
    about: typeof aboutEn;
  };
  blocks: {
${typeFields}
  };
};

/** Recursive dotted path extractor — depth-limited so TypeScript doesn't blow up. */
type DotPath<T, Depth extends number[] = []> = Depth["length"] extends 6
  ? never
  : T extends Record<string, unknown>
    ? {
        [K in keyof T & string]:
          | K
          | \`\${K}.\${DotPath<T[K], [...Depth, 1]>}\`;
      }[keyof T & string]
    : never;

/** Every dotted translation key the merged tree exposes — fed to \`titleKey\`, \`labelKey\`, … */
export type MessageKey = DotPath<MergedMessages>;
`;

writeFileSync(TYPES_OUT, typesContent);

// Format the generated files so `pnpm verify`'s format:check stays clean.
spawnSync(
  "pnpm",
  ["exec", "prettier", "--write", "--log-level", "silent", I18N_OUT, TYPES_OUT],
  {
    stdio: "inherit",
  },
);

console.log(`✓ wrote ${entries.length} block-message entries`);
console.log(`  - ${relative(ROOT, I18N_OUT)}`);
console.log(`  - ${relative(ROOT, TYPES_OUT)}`);
