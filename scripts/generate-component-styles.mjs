#!/usr/bin/env node
/**
 * Auto-generate `src/app/_component-styles.css` — the manifest of every
 * component-co-located CSS file.
 *
 * Usage: `pnpm gen:styles` (also runs as `predev` / `prebuild` /
 * `prebuild-storybook` so contributors never forget).
 *
 * Writes a deterministic, sorted list of `@import` lines so diffs are
 * reviewable. Tracked in git so CI builds without running this step (Husky
 * pre-commit re-runs it on staged components/**\/*.css changes).
 */

import { readdirSync, statSync, writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const ROOT = process.cwd();
const SRC_COMPONENTS = join(ROOT, "src", "components");
const OUT = join(ROOT, "src", "app", "_component-styles.css");

function walk(dir, acc = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      // skip node_modules / storybook caches if they ever appear
      if (entry === "node_modules" || entry.startsWith(".")) continue;
      walk(full, acc);
    } else if (entry.endsWith(".css")) {
      acc.push(full);
    }
  }
  return acc;
}

const cssFiles = walk(SRC_COMPONENTS)
  .map((abs) => relative(join(ROOT, "src"), abs).split(sep).join("/"))
  .sort();

const header = [
  "/*",
  " * AUTO-GENERATED by scripts/generate-component-styles.mjs",
  " * Do NOT edit by hand. Run `pnpm gen:styles` after adding a new",
  " * component-co-located .css file (or rely on the predev/prebuild hook).",
  " */",
  "",
];
const body = cssFiles.length
  ? cssFiles.map((p) => `@import "../${p}";`)
  : ["/* no component-co-located CSS files yet */"];
const next = [...header, ...body, ""].join("\n");

mkdirSync(join(ROOT, "src", "app"), { recursive: true });

let prev = "";
try {
  prev = readFileSync(OUT, "utf8");
} catch {
  /* first run */
}

if (prev === next) {
  console.log(`✓ ${relative(ROOT, OUT)} up to date (${cssFiles.length} files)`);
  process.exit(0);
}

writeFileSync(OUT, next);
console.log(`✓ wrote ${relative(ROOT, OUT)} (${cssFiles.length} files)`);
